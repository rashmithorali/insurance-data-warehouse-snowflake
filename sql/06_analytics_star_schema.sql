-- 2. Dimension View: Current Active Policies (SCD Type 2 filtered to IS_CURRENT = TRUE)
CREATE OR REPLACE VIEW DIM_POLICY_CURRENT AS
SELECT
    POLICY_SK,
    POLICY_ID,
    BROKER_ID,
    CUSTOMER_ID,
    PRODUCT_LINE,
    POLICY_STATUS,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    GROSS_WRITTEN_PREMIUM,
    DEDUCTIBLE,
    COVERAGE_LIMIT,
    CURRENCY
FROM INSURANCE_ANALYTICS_DB.STAGING.STG_POLICIES_SCD2
WHERE IS_CURRENT = TRUE;

-- 3. Fact View: Claims Enriched with Policy & Product Attributes
CREATE OR REPLACE VIEW FACT_CLAIMS AS
SELECT
    c.CLAIM_ID,
    c.POLICY_ID,
    c.BROKER_ID,
    p.PRODUCT_LINE,
    c.LOSS_DATE,
    c.REPORTED_DATE,
    DATEDIFF('day', c.LOSS_DATE, c.REPORTED_DATE) AS REPORTING_LAG_DAYS,
    c.CLAIM_STATUS,
    c.RESERVE_AMOUNT,
    c.PAID_AMOUNT,
    c.TOTAL_INCURRED,
    c.CURRENCY
FROM INSURANCE_ANALYTICS_DB.STAGING.STG_CLAIMS c
LEFT JOIN DIM_POLICY_CURRENT p
    ON c.POLICY_ID = p.POLICY_ID;

-- 4. Executive BI Summary View: Broker Portfolio & Loss Ratio KPIs
CREATE OR REPLACE VIEW VW_BROKER_PORTFOLIO_KPIS AS
SELECT
    b.BROKER_ID,
    b.BROKER_NAME,
    b.REGION,
    p.PRODUCT_LINE,
    COUNT(DISTINCT p.POLICY_ID) AS ACTIVE_POLICIES,
    SUM(p.GROSS_WRITTEN_PREMIUM) AS TOTAL_GWP,
    COALESCE(SUM(c.TOTAL_INCURRED), 0) AS TOTAL_INCURRED_CLAIMS,
    ROUND(
        (COALESCE(SUM(c.TOTAL_INCURRED), 0) / NULLIF(SUM(p.GROSS_WRITTEN_PREMIUM), 0)) * 100,
        2
    ) AS LOSS_RATIO_PCT
FROM DIM_BROKER b
LEFT JOIN DIM_POLICY_CURRENT p ON b.BROKER_ID = p.BROKER_ID
LEFT JOIN FACT_CLAIMS c ON p.POLICY_ID = c.POLICY_ID
GROUP BY 1, 2, 3, 4;

-- Test your Gold KPI View
SELECT * FROM VW_BROKER_PORTFOLIO_KPIS ORDER BY BROKER_ID, PRODUCT_LINE;

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_INSURANCE_ANALYTICS_XS;
USE SCHEMA INSURANCE_ANALYTICS_DB.RAW;

-- 1. Create Raw Landing Tables (storing raw JSON payload + ingestion metadata)
CREATE OR REPLACE TABLE RAW_POLICIES (
    RAW_PAYLOAD VARIANT,
    SOURCE_FILE_NAME VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE RAW_CLAIMS (
    RAW_PAYLOAD VARIANT,
    SOURCE_FILE_NAME VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 2. Load data from Stage into Raw Tables
COPY INTO RAW_POLICIES (RAW_PAYLOAD, SOURCE_FILE_NAME)
FROM (
    SELECT $1, METADATA$FILENAME
    FROM @INSURANCE_LANDING_STAGE/policies_batch_01.json
)
FILE_FORMAT = (TYPE = 'JSON');

COPY INTO RAW_CLAIMS (RAW_PAYLOAD, SOURCE_FILE_NAME)
FROM (
    SELECT $1, METADATA$FILENAME
    FROM @INSURANCE_LANDING_STAGE/claims_batch_01.json
)
FILE_FORMAT = (TYPE = 'JSON');

-- 3. Verify loaded row counts and inspect JSON structure
SELECT COUNT(*) AS POLICY_COUNT FROM RAW_POLICIES;
SELECT COUNT(*) AS CLAIM_COUNT FROM RAW_CLAIMS;
SELECT * FROM RAW_POLICIES LIMIT 5;
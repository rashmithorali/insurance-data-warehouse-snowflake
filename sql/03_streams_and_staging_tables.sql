USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_INSURANCE_ANALYTICS_XS;
USE DATABASE INSURANCE_ANALYTICS_DB;

-- 1. Create Streams on RAW tables to capture incremental inserts (CDC)
USE SCHEMA RAW;

CREATE OR REPLACE STREAM RAW_POLICIES_STREAM ON TABLE RAW_POLICIES APPEND_ONLY = TRUE;
CREATE OR REPLACE STREAM RAW_CLAIMS_STREAM ON TABLE RAW_CLAIMS APPEND_ONLY = TRUE;

-- 2. Create Staging Tables (SCD Type 2 for Policies, Curated for Claims)
USE SCHEMA STAGING;

CREATE OR REPLACE TABLE STG_POLICIES_SCD2 (
    POLICY_SK VARCHAR DEFAULT UUID_STRING(),
    POLICY_ID VARCHAR,
    BROKER_ID VARCHAR,
    CUSTOMER_ID VARCHAR,
    PRODUCT_LINE VARCHAR,
    POLICY_STATUS VARCHAR,
    EFFECTIVE_DATE DATE,
    EXPIRY_DATE DATE,
    GROSS_WRITTEN_PREMIUM NUMBER(12,2),
    DEDUCTIBLE NUMBER(10,2),
    COVERAGE_LIMIT NUMBER(12,2),
    CURRENCY VARCHAR,
    VALID_FROM TIMESTAMP_NTZ,
    VALID_TO TIMESTAMP_NTZ,
    IS_CURRENT BOOLEAN
);

CREATE OR REPLACE TABLE STG_CLAIMS (
    CLAIM_ID VARCHAR PRIMARY KEY,
    POLICY_ID VARCHAR,
    BROKER_ID VARCHAR,
    LOSS_DATE DATE,
    REPORTED_DATE DATE,
    CLAIM_STATUS VARCHAR,
    RESERVE_AMOUNT NUMBER(12,2),
    PAID_AMOUNT NUMBER(12,2),
    TOTAL_INCURRED NUMBER(12,2),
    CURRENCY VARCHAR,
    UPDATED_AT TIMESTAMP_NTZ
);

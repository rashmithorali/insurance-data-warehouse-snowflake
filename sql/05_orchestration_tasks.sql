USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_INSURANCE_ANALYTICS_XS;
USE SCHEMA INSURANCE_ANALYTICS_DB.STAGING;

-- 1. Create a Task that checks every 5 minutes if new data arrived in either Stream
CREATE OR REPLACE TASK TASK_PROCESS_INSURANCE_CDC
  WAREHOUSE = WH_INSURANCE_ANALYTICS_XS
  SCHEDULE = '5 MINUTE'
  WHEN SYSTEM$STREAM_HAS_DATA('INSURANCE_ANALYTICS_DB.RAW.RAW_POLICIES_STREAM')
    OR SYSTEM$STREAM_HAS_DATA('INSURANCE_ANALYTICS_DB.RAW.RAW_CLAIMS_STREAM')
AS
  CALL INSURANCE_ANALYTICS_DB.STAGING.SP_PROCESS_INSURANCE_CDC();

-- 2. Tasks are created in a SUSPENDED state by default; resume it to activate
ALTER TASK TASK_PROCESS_INSURANCE_CDC RESUME;

-- 3. Verify Task status and schedule
SHOW TASKS LIKE 'TASK_PROCESS_INSURANCE_CDC';
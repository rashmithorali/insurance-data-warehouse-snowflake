USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_INSURANCE_ANALYTICS_XS;
USE SCHEMA INSURANCE_ANALYTICS_DB.ANALYTICS;

-- 1. Create a Mapping Table linking Snowflake Roles to Tenant Broker IDs
CREATE OR REPLACE TABLE BROKER_SECURITY_MAPPING (
    SNOWFLAKE_ROLE VARCHAR,
    ALLOWED_BROKER_ID VARCHAR
);

INSERT INTO BROKER_SECURITY_MAPPING VALUES
    ('ROLE_BROKER_001', 'BRK_NL_001'),
    ('ROLE_BROKER_002', 'BRK_NL_002');

-- 2. Create a Row Access Policy
-- Admins see all rows; specific broker roles only see their mapped BROKER_ID
CREATE OR REPLACE ROW ACCESS POLICY RAP_BROKER_ISOLATION
AS (BROKER_ID VARCHAR) RETURNS BOOLEAN ->
    CURRENT_ROLE() = 'ACCOUNTADMIN'
    OR EXISTS (
        SELECT 1
        FROM INSURANCE_ANALYTICS_DB.ANALYTICS.BROKER_SECURITY_MAPPING m
        WHERE m.SNOWFLAKE_ROLE = CURRENT_ROLE()
          AND m.ALLOWED_BROKER_ID = BROKER_ID
    );

-- 3. Attach the Row Access Policy to your underlying Staging tables
ALTER TABLE INSURANCE_ANALYTICS_DB.STAGING.STG_POLICIES_SCD2
ADD ROW ACCESS POLICY RAP_BROKER_ISOLATION ON (BROKER_ID);

ALTER TABLE INSURANCE_ANALYTICS_DB.STAGING.STG_CLAIMS
ADD ROW ACCESS POLICY RAP_BROKER_ISOLATION ON (BROKER_ID);

-- 4. Test Multi-Tenant Isolation by creating a restricted Broker Role
CREATE OR REPLACE ROLE ROLE_BROKER_001;
GRANT USAGE ON WAREHOUSE WH_INSURANCE_ANALYTICS_XS TO ROLE ROLE_BROKER_001;
GRANT USAGE ON DATABASE INSURANCE_ANALYTICS_DB TO ROLE ROLE_BROKER_001;
GRANT USAGE ON SCHEMA INSURANCE_ANALYTICS_DB.ANALYTICS TO ROLE ROLE_BROKER_001;
GRANT SELECT ON ALL VIEWS IN SCHEMA INSURANCE_ANALYTICS_DB.ANALYTICS TO ROLE ROLE_BROKER_001;
GRANT ROLE ROLE_BROKER_001 TO USER IDENTIFIER(CURRENT_USER());

-- Switch to Broker 001's role and query the exact same view!
USE ROLE ROLE_BROKER_001;
SELECT * FROM INSURANCE_ANALYTICS_DB.ANALYTICS.DIM_POLICY_CURRENT;
-- Notice: Only BRK_NL_001 rows appear! BRK_NL_002 and BRK_NL_003 are completely hidden.

-- Switch back to ACCOUNTADMIN when finished testing
USE ROLE ACCOUNTADMIN;